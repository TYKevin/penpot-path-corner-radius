import { readFile, writeFile, mkdir, cp } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
await mkdir(`${root}dist`, { recursive: true });
const { version } = JSON.parse(await readFile(`${root}package.json`, 'utf8'));
const modules = ['geometry.mjs', 'outline.mjs', 'state.mjs', 'plugin.mjs'];
const source = await Promise.all(
  modules.map((name) => readFile(`${root}src/${name}`, 'utf8')),
);
const bundle = source
  .map((text) =>
    text
      .replace(/^import\b[\s\S]*?\sfrom\s+['"][^'"]+['"];?\r?\n/gm, '')
      .replace(/^export /gm, ''),
  )
  .join('\n');
await writeFile(
  `${root}dist/plugin.js`,
  `// Path Corner Radius v${version} — generated by scripts/build.mjs\n(() => {\n${bundle}\nstartPlugin(penpot);\n})();\n`,
);
for (const name of [
  'index.html',
  'style.css',
  'ui.mjs',
  'i18n.mjs',
  'geometry.mjs',
  'outline.mjs',
  'state.mjs',
  'icon.svg',
]) {
  await cp(`${root}src/${name}`, `${root}dist/${name}`);
}
await cp(`${root}manifest.json`, `${root}dist/manifest.json`);
console.log(
  'Built dist/: manifest.json, plugin.js, UI and local geometry modules.',
);
